// Scam-playbook library: how each fraud type works, its red flags, and how
// to stay safe — with the live count of verified reports per type.
export default async function GuidePage() {
  const counts = new Map<string, number>();
  try {
    const groups = await prisma.report.groupBy({
      by: ["scamType"],
      where: { status: "approved" },
      _count: { _all: true },
    });
    for (const g of groups) counts.set(g.scamType, g._count._all);
  } catch { /* counts simply stay hidden */ }

  return (
    <main className="wrap">
      <div className="pagehead">
        <h2>🎯 প্রতারকের কৌশল</h2>
        <p className="small" style={{ maxWidth: 640 }}>
          কৌশল চিনলে অর্ধেক বাঁচা। বাংলাদেশে সবচেয়ে বেশি হওয়া প্রতারণার ধরনগুলো
          কীভাবে কাজ করে আর কোন লক্ষণ দেখলে থামবেন — এক জায়গায় সব।
        </p>
      </div>
      <section style={{ paddingTop: 4 }}>
        <div className="list">
          {Object.entries(SCAM_TYPES).map(([key, label]) => {
            const g = GUIDES[key];
            if (!g) return null;
            const n = counts.get(key) || 0;
            return (
              <article className="item" key={key}>
                <div className="top">
                  <strong style={{ fontSize: 17 }}>{g.icon} {label}</strong>
                  {n > 0 && <span className="tag warn">যাচাইকৃত অভিযোগ: {toBn(n)}টি</span>}
                </div>
                <p style={{ margin: "8px 0" }}>{g.how}</p>
                <strong className="small">🚩 লাল পতাকা (এগুলো দেখলেই সতর্ক):</strong>
                <ul style={{ margin: "6px 0 10px", paddingLeft: 20 }}>
                  {g.signs.map((s, i) => <li key={i} className="small" style={{ marginBottom: 3 }}>{s}</li>)}
                </ul>
                <p className="small" style={{ margin: 0 }}>✅ <strong>বাঁচার উপায়:</strong> {g.safe}</p>
              </article>
            );
          })}
        </div>

        <div className="item" style={{ marginTop: 22 }}>
          <strong>সন্দেহজনক নম্বর হাতে পেয়েছেন?</strong>
          <p className="small">টাকা পাঠানোর আগে এক মিনিট — নম্বরটি যাচাই করে নিন।</p>
          <a className="btn" href="/" style={{ display: "inline-block" }}>এখনই যাচাই করুন</a>
        </div>
      </section>
    </main>
  );
}
